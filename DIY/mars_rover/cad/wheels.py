"""Mars rover: the two wheels side by side, as one picture.

Draws the drum (drum.py) and the two-plate wheel (gear_plate.py) in 3D to the same scale, with planks seated round
their lower halves and their loops, and writes mars-rover-wheels.png. The shapes come from the two generators; three.js
(r128, from cdnjs) renders them in headless Chrome, so a run needs the network.
"""
from __future__ import annotations

import json
import math
import pathlib
import subprocess
import tempfile

import drum as d
import gear_plate as g

HERE = pathlib.Path(__file__).resolve().parent
NAME = "mars-rover-wheels"
W, H = 1600, 900


def wheel_data():
    dpts, _ = g.outline(z=d.Z, r_pin=d.R_PIN, r_tip=d.R_TIP, seat_r=d.SEAT_R, flank=d.FLANK)
    ppts, _ = g.outline()
    tube = lambda od, idd, l: math.pi / 4 * (od ** 2 - idd ** 2) * l * 8.5e-3          # noqa: E731  brass, g
    drum_g = d.HALVES * (g.poly_area(dpts) - math.pi * (d.HOLE / 2) ** 2) * d.THICK * 2.70e-3 + tube(*d.TUBE4, d.HUB_L)
    plate_g = (g.poly_area(ppts) - math.pi * (g.HOLE / 2) ** 2) * g.THICK * 7.93e-3
    plates_g = 2 * plate_g + tube(*g.TUBE4, 11.5) + tube(*g.TUBE5, g.SPACER)
    plank_end = g.PLANK_L / 2                                                        # the plates sit 0.4 inside it
    halves = [((k - (d.HALVES - 1) / 2) * d.THICK, d.THICK) for k in range(d.HALVES)]
    drum = dict(pts=dpts, hole=d.HOLE, parts=halves, paint=[d.WIDTH / 2, -d.WIDTH / 2], rf=d.RF,
                hub=(d.TUBE4[0], d.TUBE4[1], d.HUB_L, (0.5 - d.HUB_IN) / 2), spacer=None, pin_d=d.PIN_D, pin_wall=d.TUBE_WALL,
                pin_l=d.PIN_L, face_l=d.PLANK_L, stub=d.PLANK_L / 2 + d.PIN_OUT / 2,
                planks=[(p, f) for p, f in d.planks_round() if p[1] <= 0.5], grams=drum_g)
    zp = g.SPACER / 2 + g.THICK / 2
    plates = dict(pts=ppts, hole=g.HOLE, parts=[(-zp, g.THICK), (zp, g.THICK)], paint=[zp + g.THICK / 2], rf=g.RF,
                  hub=(g.TUBE4[0], g.TUBE4[1], 11.5, 0.0), spacer=(g.TUBE5[0], g.TUBE5[1], g.SPACER), pin_d=g.ROD1, pin_wall=0,
                  pin_l=g.PLANK_L + 2 * g.PIN_OUT, face_l=g.PLANK_L, stub=plank_end + g.PIN_OUT / 2,
                  planks=[(p, f) for p, f in g.planks_round() if p[1] <= 0.5], grams=plates_g)
    return drum, plates


def page(drum, plates):
    data = json.dumps(dict(drum=drum, plates=plates, loop_r=g.LOOP_WIRE / 2))
    labels = [
        ("The drum: two halves, one wheel",
         [f"two 3/8 in 6061 aluminium halves, laser cut, glued: {d.WIDTH:.1f} mm wide", f"{d.Z} seats, {2 * d.R_TIP:.1f} mm across, {drum['grams']:.1f} g with its hub",
          "planks: a 3/32 in brass tube and two 1 mm rods", f"{d.PLANKS} planks a side; order ten halves"]),
        ("Two plates a wheel",
         [f"1.52 mm 304 stainless, laser cut, 8.2 mm apart", f"{g.Z} teeth, {2 * g.R_TIP:.1f} mm across, {plates['grams']:.1f} g with its tubes",
          "planks: three 1 mm brass rods", "40 planks a side; order ten plates"]),
    ]
    lab_html = "".join(
        f'<div class="lab" id="lab{i}"><div class="h">{h}</div>' + "".join(f'<div class="t">{t}</div>' for t in lines) + "</div>"
        for i, (h, lines) in enumerate(labels))
    return f"""<!doctype html><meta charset=utf-8>
<style>html,body{{margin:0;background:#fbfaf7;font-family:Helvetica,Arial,sans-serif;color:#1b1d21}}
#t{{position:absolute;left:40px;top:30px}} #t .h{{font-size:32px;font-weight:700}} #t .t{{font-size:18px;color:#5d636c;margin-top:8px}}
.lab{{position:absolute;width:520px;text-align:center}} .lab .h{{font-size:24px;font-weight:700;margin-bottom:8px}} .lab .t{{font-size:17px;color:#5d636c;line-height:1.5}}
#f{{position:absolute;left:40px;bottom:22px;font-size:14px;color:#5d636c}}</style>
<div id="t"><div class="h">The wheel, two ways</div><div class="t">Same scale. Faces sprayed canvas white with the teeth bare; brass hubs and planks; nickel-silver loops on the pin ends.</div></div>
{lab_html}
<div id="f">Generated by mars_rover/cad/wheels.py from drum.py and gear_plate.py.</div>
<script src="https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js"></script>
<script>
const D = {data};
const W = {W}, H = {H};
const renderer = new THREE.WebGLRenderer({{antialias: true, preserveDrawingBuffer: true}});
renderer.setPixelRatio(1); renderer.setSize(W, H); renderer.setClearColor(0xfbfaf7);
renderer.domElement.style.position = 'absolute'; renderer.domElement.style.left = '0'; renderer.domElement.style.top = '0';
document.body.prepend(renderer.domElement);
const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera(16, W / H, 10, 2000);
camera.position.set(0, 52, 250); camera.lookAt(0, -2, 0);
scene.add(new THREE.AmbientLight(0xffffff, 0.42));
const key = new THREE.DirectionalLight(0xffffff, 0.75); key.position.set(80, 140, 160); scene.add(key);
const fill = new THREE.DirectionalLight(0xffffff, 0.32); fill.position.set(-140, 20, 80); scene.add(fill);
const rim = new THREE.DirectionalLight(0xffffff, 0.25); rim.position.set(0, -60, -160); scene.add(rim);
const M = {{
  alu: new THREE.MeshPhongMaterial({{color: 0xc9cdd3, specular: 0x5a5a5a, shininess: 36}}),
  steel: new THREE.MeshPhongMaterial({{color: 0xbcc1c7, specular: 0x777777, shininess: 70}}),
  ivory: new THREE.MeshPhongMaterial({{color: 0xf3eee1, specular: 0x222222, shininess: 12, side: THREE.DoubleSide}}),
  brass: new THREE.MeshPhongMaterial({{color: 0xc9a04a, specular: 0x7a6230, shininess: 44}}),
  bore: new THREE.MeshPhongMaterial({{color: 0x6b5a35, side: THREE.BackSide}}),
  loop: new THREE.MeshPhongMaterial({{color: 0xb9bdc3, specular: 0x888888, shininess: 60}}),
}};
function shape(pts, hole) {{
  const s = new THREE.Shape();
  pts.forEach((p, i) => i ? s.lineTo(p[0], p[1]) : s.moveTo(p[0], p[1])); s.closePath();
  const h = new THREE.Path(); h.absarc(0, 0, hole / 2, 0, Math.PI * 2, true); s.holes.push(h); return s;
}}
function rodZ(r, len, x, y, z, mat, seg = 28, open = false) {{
  const geo = new THREE.CylinderGeometry(r, r, len, seg, 1, open); geo.rotateX(Math.PI / 2);
  const m = new THREE.Mesh(geo, mat); m.position.set(x, y, z); return m;
}}
function tubeZ(ro, ri, len, x, y, z) {{
  const grp = new THREE.Group();
  grp.add(rodZ(ro, len, x, y, z, M.brass, 40, ri > 0));
  if (ri > 0) {{
    const inner = new THREE.CylinderGeometry(ri, ri, len + 0.02, 32, 1, true); inner.rotateX(Math.PI / 2);
    const mi = new THREE.Mesh(inner, M.bore); mi.position.set(x, y, z); grp.add(mi);
    for (const e of [1, -1]) {{
      const end = new THREE.Mesh(new THREE.RingGeometry(ri, ro, 40), M.brass);
      end.position.set(x, y, z + e * (len / 2 + 0.01)); if (e < 0) end.rotation.y = Math.PI; grp.add(end);
      const dark = new THREE.Mesh(new THREE.CircleGeometry(ri, 32), new THREE.MeshBasicMaterial({{color: 0x3a3226}}));
      dark.position.set(x, y, z + e * (len / 2 - 0.4)); if (e < 0) dark.rotation.y = Math.PI; grp.add(dark);
    }}
  }}
  return grp;
}}
function loop(p1, p2, r, z) {{
  const pts = [], n = 18, a = Math.atan2(p2[1] - p1[1], p2[0] - p1[0]);
  for (let k = 0; k <= n; k++) {{ const t = a - Math.PI / 2 + Math.PI * k / n; pts.push(new THREE.Vector3(p2[0] + r * Math.cos(t), p2[1] + r * Math.sin(t), z)); }}
  for (let k = 0; k <= n; k++) {{ const t = a + Math.PI / 2 + Math.PI * k / n; pts.push(new THREE.Vector3(p1[0] + r * Math.cos(t), p1[1] + r * Math.sin(t), z)); }}
  const curve = new THREE.CatmullRomCurve3(pts, true);
  return new THREE.Mesh(new THREE.TubeGeometry(curve, 96, D.loop_r, 10, true), M.loop);
}}
function wheel(w, mat) {{
  const grp = new THREE.Group();
  for (const [zc, t] of w.parts) {{
    const geo = new THREE.ExtrudeGeometry(shape(w.pts, w.hole), {{depth: t, bevelEnabled: false, curveSegments: 48}});
    geo.translate(0, 0, zc - t / 2); grp.add(new THREE.Mesh(geo, mat));
  }}
  for (const zf of w.paint) {{
    const ring = new THREE.Mesh(new THREE.RingGeometry(w.hub[0] / 2 + 0.05, w.rf - 0.6, 96), M.ivory);
    ring.position.z = zf + Math.sign(zf) * 0.02; grp.add(ring);
  }}
  grp.add(tubeZ(w.hub[0] / 2, w.hub[1] / 2, w.hub[2], 0, 0, w.hub[3]));
  if (w.spacer) grp.add(tubeZ(w.spacer[0] / 2, w.spacer[1] / 2, w.spacer[2], 0, 0, 0));
  for (const [pin, faces] of w.planks) {{
    if (w.pin_wall > 0) grp.add(tubeZ(w.pin_d / 2, w.pin_d / 2 - w.pin_wall, w.pin_l, pin[0], pin[1], 0));
    else grp.add(rodZ(w.pin_d / 2, w.pin_l, pin[0], pin[1], 0, M.brass));
    for (const f of faces) grp.add(rodZ(0.5, w.face_l, f[0], f[1], 0, M.brass));
  }}
  const pins = w.planks.map(p => p[0]).sort((a, b) => Math.atan2(a[1], a[0]) - Math.atan2(b[1], b[0]));
  for (let i = 0; i + 1 < pins.length; i++)
    for (const s of [1, -1]) grp.add(loop(pins[i], pins[i + 1], w.pin_d / 2 + 0.05 + D.loop_r, s * w.stub));
  return grp;
}}
const left = wheel(D.drum, M.alu), right = wheel(D.plates, M.steel);
for (const [w, x] of [[left, -25], [right, 25]]) {{ w.rotation.y = 0.62; w.position.x = x; w.position.y = 3; scene.add(w); }}
renderer.render(scene, camera);
for (const [i, x] of [[0, -25], [1, 25]]) {{
  const v = new THREE.Vector3(x, -18, 0).project(camera);
  const el = document.getElementById('lab' + i);
  el.style.left = ((v.x + 1) / 2 * W - 260) + 'px'; el.style.top = ((1 - v.y) / 2 * H) + 'px';
}}
document.title = 'done';
</script>"""


def main():
    drum, plates = wheel_data()
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / "w.html"
        src.write_text(page(drum, plates))
        subprocess.run(["google-chrome", "--headless=new", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist",
                        "--hide-scrollbars", f"--window-size={W},{H}", "--virtual-time-budget=15000",
                        f"--screenshot={HERE / (NAME + '.png')}", f"file://{src}"], check=True, capture_output=True, timeout=180)
    print(f"drum {drum['grams']:.1f} g, two plates {plates['grams']:.1f} g; wrote {NAME}.png")


if __name__ == "__main__":
    main()
