#!/usr/bin/env python3
"""Turn two system bitmap fonts into the C tables the hologram draws with.

    python3 tools/mkfont.py            # writes main/font_5x8.h and main/font_8x16.h

Small text: the X11 "misc-fixed" 5x8 font (public domain), /usr/share/fonts/X11/misc/5x8.pcf.gz,
drawn at a 6-pixel advance: 19 characters across the cube's 116 columns, 8 lines down the 64 rows.
Big text: Terminus 8x16 (SIL Open Font License 1.1, (c) Dimitar Zhekov),
/usr/share/consolefonts/Lat15-Terminus16.psf.gz, drawn at an 8-pixel advance: 14 characters a line,
3 lines. Both tables hold ASCII 32..126 and Latin-1 160..255 (191 glyphs); text.c maps curly quotes,
dashes and the ellipsis onto them. Needs Pillow for the PCF file; the PSF file is read directly.
"""
import gzip
import io
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "main")
CODEPOINTS = list(range(32, 127)) + list(range(160, 256))


def read_psf(path):
    """PSF1 or PSF2 -> (width, height, {codepoint: [row ints, MSB = left]})."""
    data = gzip.open(path).read()
    if data[:2] == b"\x36\x04":  # PSF1
        mode, charsize = data[2], data[3]
        length = 512 if mode & 1 else 256
        width, height, hdr, stride = 8, charsize, 4, 1
        table = {}
        if mode & 2:
            pos = hdr + length * charsize
            for gi in range(length):
                while True:
                    (u,) = struct.unpack_from("<H", data, pos)
                    pos += 2
                    if u == 0xFFFF:
                        break
                    if u == 0xFFFE:
                        while struct.unpack_from("<H", data, pos)[0] != 0xFFFF:
                            pos += 2
                        pos += 2
                        break
                    table.setdefault(u, gi)
    elif data[:4] == b"\x72\xb5\x4a\x86":  # PSF2
        _, _, hdr, flags, length, charsize, height, width = struct.unpack_from("<8I", data, 0)
        stride = (width + 7) // 8
        table = {}
        if flags & 1:
            pos = hdr + length * charsize
            for gi in range(length):
                seq = b""
                while data[pos] != 0xFF:
                    if data[pos] == 0xFE:
                        while data[pos] != 0xFF:
                            pos += 1
                        break
                    seq += bytes([data[pos]])
                    pos += 1
                pos += 1
                try:
                    for cp in seq.decode("utf-8"):
                        table.setdefault(ord(cp), gi)
                except UnicodeDecodeError:
                    pass
    else:
        raise ValueError(f"{path}: not a PSF font")
    if not table:
        table = {i: i for i in range(length)}
    glyphs = {}
    for cp, gi in table.items():
        g = data[hdr + gi * charsize:hdr + (gi + 1) * charsize]
        glyphs[cp] = [int.from_bytes(g[y * stride:(y + 1) * stride], "big") >> (stride * 8 - width) for y in range(height)]
    return width, height, glyphs


def read_pcf(path, width, height):
    """PCF via Pillow -> {codepoint: [row ints, MSB = left]} for Latin-1 codepoints."""
    from PIL import Image, ImageDraw, ImageFont, PcfFontFile
    pcf = PcfFontFile.PcfFontFile(io.BytesIO(gzip.open(path).read()))
    tmp = os.path.join(HERE, ".pcf_tmp")
    pcf.save(tmp)
    font = ImageFont.load(tmp + ".pil")
    glyphs = {}
    for cp in CODEPOINTS:
        img = Image.new("1", (width * 2, height * 2), 0)
        ImageDraw.Draw(img).text((0, 0), chr(cp), font=font, fill=1)
        rows = []
        for y in range(height):
            v = 0
            for x in range(width):
                v = (v << 1) | (1 if img.getpixel((x, y)) else 0)
            rows.append(v)
        glyphs[cp] = rows
    for ext in (".pil", ".pbm"):
        try:
            os.remove(tmp + ext)
        except OSError:
            pass
    return glyphs


def rows_to_columns(rows, width, height):
    """Column bytes, bit 0 = top row (the SSD1306 page layout), for fonts up to 8 rows tall."""
    assert height <= 8
    cols = []
    for x in range(width):
        v = 0
        for y in range(height):
            if (rows[y] >> (width - 1 - x)) & 1:
                v |= 1 << y
        cols.append(v)
    return cols


def write_header(name, width, height, glyphs, layout, source, licence):
    path = os.path.join(OUT, f"{name}.h")
    n = len(CODEPOINTS)
    per = width if layout == "columns" else height
    lines = [
        f"// Generated by tools/mkfont.py from {source}; do not edit.",
        f"// {licence}",
        f"// {n} glyphs: ASCII 32..126 then Latin-1 160..255, {per} bytes each,",
        ("// one byte per column, bit 0 = top row." if layout == "columns" else "// one byte per row, bit 7 = left column."),
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define {name.upper()}_W {width}",
        f"#define {name.upper()}_H {height}",
        f"#define {name.upper()}_GLYPHS {n}",
        f"#define {name.upper()}_BYTES {per}",
        "",
        f"static const uint8_t {name}[{n}][{per}] = {{",
    ]
    for cp in CODEPOINTS:
        rows = glyphs.get(cp) or glyphs[ord("?")]
        data = rows_to_columns(rows, width, height) if layout == "columns" else rows
        label = chr(cp) if cp != 92 and cp != 42 and cp != 47 else {92: "backslash", 42: "asterisk", 47: "slash"}[cp]
        lines.append("    {" + ", ".join(f"0x{b:02X}" for b in data) + f"}},  // U+{cp:04X} {label}")
    lines.append("};")
    lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {os.path.relpath(path)}: {n} glyphs x {per} bytes = {n * per} bytes")


def main():
    small = read_pcf("/usr/share/fonts/X11/misc/5x8.pcf.gz", 5, 8)
    write_header("font_5x8", 5, 8, small, "columns",
                 "/usr/share/fonts/X11/misc/5x8.pcf.gz (X11 misc-fixed 5x8)",
                 "misc-fixed is public domain.")
    w, h, big = read_psf("/usr/share/consolefonts/Lat15-Terminus16.psf.gz")
    assert (w, h) == (8, 16), (w, h)
    write_header("font_8x16", 8, 16, big, "rows",
                 "/usr/share/consolefonts/Lat15-Terminus16.psf.gz (Terminus 8x16)",
                 "Terminus Font (c) 2020 Dimitar Toshkov Zhekov, SIL Open Font License 1.1; this table is a bitmap copy, not the font.")
    missing = [cp for cp in CODEPOINTS if cp not in big]
    if missing:
        print("Terminus missing codepoints:", missing, file=sys.stderr)


if __name__ == "__main__":
    main()
